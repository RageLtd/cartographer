//! Load tree-sitter grammars from shared libraries on the host.
//!
//! A grammar built with `tree-sitter build` is a shared object exporting one
//! function, `tree_sitter_<name>`, that returns a pointer to its `TSLanguage`.
//! This module opens such a library, checks the grammar's ABI against the
//! linked tree-sitter runtime, and hands back a [`Language`].

use std::path::Path;

use libloading::{Library, Symbol};
use tree_sitter::ffi::{ts_language_abi_version, TSLanguage};
use tree_sitter::{Language, LANGUAGE_VERSION, MIN_COMPATIBLE_LANGUAGE_VERSION};

type LanguageConstructor = unsafe extern "C" fn() -> *const TSLanguage;

/// The symbol a CLI-built grammar exports: `tree_sitter_<name>`, with dashes
/// normalised to underscores the way the CLI does.
pub fn language_symbol(grammar_name: &str) -> String {
    format!("tree_sitter_{}", grammar_name.replace('-', "_"))
}

/// Load the grammar exported as `symbol` from the shared library at `library_path`.
///
/// Only call this for libraries under the user's own Cartographer data
/// directory. Opening a shared object runs its initialisers, so a grammar path
/// must never be taken from the project being indexed.
pub fn load_grammar(library_path: &Path, symbol: &str) -> Result<Language, String> {
    let display = library_path.display();

    // SAFETY: see the doc comment — the caller vouches for the library's origin.
    let library = unsafe { Library::new(library_path) }
        .map_err(|e| format!("Failed to load grammar library {display}: {e}"))?;

    // SAFETY: `tree_sitter_<name>` is generated by the tree-sitter CLI with
    // exactly this signature; a wrong symbol name fails the lookup, not the call.
    let constructor: Symbol<LanguageConstructor> = unsafe { library.get(symbol.as_bytes()) }
        .map_err(|e| format!("Grammar library {display} has no `{symbol}` symbol: {e}"))?;

    // SAFETY: calling the generated constructor, which returns a pointer to a
    // static `TSLanguage` inside the library.
    let ptr = unsafe { constructor() };
    if ptr.is_null() {
        return Err(format!("`{symbol}` in {display} returned a null language"));
    }

    // Read the ABI before constructing a `Language`: the version is the first
    // field of `TSLanguage` in every ABI, so this is safe even for grammars
    // too old or new for the rest of the struct layout to be trusted.
    // SAFETY: `ptr` is non-null and points at a live `TSLanguage`.
    let abi = unsafe { ts_language_abi_version(ptr) } as usize;
    if !(MIN_COMPATIBLE_LANGUAGE_VERSION..=LANGUAGE_VERSION).contains(&abi) {
        return Err(format!(
            "Grammar {display} targets tree-sitter ABI {abi}; this build supports \
             {MIN_COMPATIBLE_LANGUAGE_VERSION}..={LANGUAGE_VERSION}. Rebuild it with a \
             tree-sitter CLI that emits ABI {LANGUAGE_VERSION}."
        ));
    }

    // SAFETY: non-null, ABI-compatible, and owned by a library we never unload.
    let language = unsafe { Language::from_raw(ptr) };

    // The `Language` points into the library's mapped pages, so dropping the
    // handle (which would `dlclose`) must never happen. Grammars live for the
    // whole process; leaking the handle is the intended lifetime.
    std::mem::forget(library);

    Ok(language)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser::fixtures::{compile_tiny_grammar, TINY_GRAMMAR_NAME};

    #[test]
    fn language_symbol_follows_cli_naming() {
        assert_eq!(language_symbol("python"), "tree_sitter_python");
        assert_eq!(language_symbol("c-sharp"), "tree_sitter_c_sharp");
    }

    #[test]
    fn missing_library_names_the_path() {
        let err = load_grammar(Path::new("/nonexistent/dir/missing.so"), "tree_sitter_x")
            .expect_err("missing library must fail");
        assert!(err.contains("/nonexistent/dir/missing.so"), "{err}");
    }

    #[test]
    fn missing_symbol_names_the_symbol() {
        let dir = tempfile::tempdir().expect("tempdir");
        let Some(so) = compile_tiny_grammar(dir.path()) else {
            return;
        };
        let err = load_grammar(&so, "tree_sitter_not_here").expect_err("wrong symbol must fail");
        assert!(err.contains("tree_sitter_not_here"), "{err}");
    }

    #[test]
    fn loads_fixture_grammar_and_parses_with_it() {
        let dir = tempfile::tempdir().expect("tempdir");
        let Some(so) = compile_tiny_grammar(dir.path()) else {
            return;
        };

        let language = load_grammar(&so, &language_symbol(TINY_GRAMMAR_NAME))
            .expect("fixture grammar should load");
        assert!(
            (MIN_COMPATIBLE_LANGUAGE_VERSION..=LANGUAGE_VERSION).contains(&language.abi_version())
        );

        let mut parser = tree_sitter::Parser::new();
        parser
            .set_language(&language)
            .expect("parser accepts the grammar");
        let tree = parser
            .parse("use \"./util\";\npub fn main() {}\n", None)
            .expect("parse succeeds");

        let root = tree.root_node();
        assert_eq!(root.kind(), "source_file");
        assert!(!root.has_error(), "{}", root.to_sexp());
        let kinds: Vec<&str> = (0..root.child_count())
            .filter_map(|i| root.child(i).map(|n| n.kind()))
            .collect();
        assert_eq!(kinds, vec!["import_statement", "function_definition"]);
    }
}
